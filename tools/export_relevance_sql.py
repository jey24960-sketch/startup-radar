"""Generate a SQL mirror of the GFC relevance rules from radar/relevance.py.

Used to classify opportunities that are already stored, without re-running the
collection pipeline against production. The rule tables in radar/relevance.py
remain the single source of truth: this file only transcribes them, so the SQL
must always be regenerated rather than edited by hand.

    python -m tools.export_relevance_sql > /tmp/relevance.sql

The generated function is an operator backfill aid, not part of the weekly
publication path, which always uses the Python classifier.
"""
import sys

from radar import relevance


def sql_regex(pattern):
    # POSIX ARE spells the word boundary \y; everything else used by the rule
    # tables (\s, (?:...), {n,m}, [^\n], alternation) is shared with Python.
    return pattern.replace('\\b', '\\y').replace("'", "''")


def quote(label):
    return "'" + label.replace("'", "''") + "'"


def branches(rules, target, subject='t'):
    """First match wins, mirroring the Python `found[0]['label']` reason."""
    lines = []
    for label, compiled in rules:
        lines.append(f"  if {target} is null and {subject} ~* '{sql_regex(compiled.pattern)}' then\n"
                     f"    {target}:={quote(label)}; end if;")
    return '\n'.join(lines)


def collected(rules, target, subject='t', indent='  '):
    """Every match, de-duplicated and joined, mirroring the Python ' · ' join."""
    lines = []
    for label, compiled in rules:
        # The ::text casts matter: `text[] || 'literal'` parses the literal as an
        # array literal and fails at runtime on any value containing '·'.
        lines.append(f"{indent}if {subject} ~* '{sql_regex(compiled.pattern)}' and not {target} @> array[{quote(label)}::text] then\n"
                     f"{indent}  {target}:={target}||{quote(label)}::text; end if;")
    return '\n'.join(lines)


def curation_branches():
    fields = {'title': 'title_text', 'applicant': 'applicant_text', 'all': 't'}
    lines = []
    for label, required, exempt in relevance.CURATION_EXCLUSION:
        conditions = [f"{fields[key]} ~* '{sql_regex(pattern.pattern)}'"
                      for key, pattern in required.items()]
        conditions.extend(f"not ({fields[key]} ~* '{sql_regex(pattern.pattern)}')"
                          for key, pattern in exempt.items())
        lines.append(f" if {' and '.join(conditions)} then\n"
                     "  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',\n"
                     f"   'applicability','UNKNOWN','startup_leverage_reason',{quote(label)},'restriction_summary',null); end if;")
    return '\n'.join(lines)


def generate():
    def evidence(field, limit):
        value = f"coalesce({field},'')"
        return value if limit is None else f"left({value},{limit})"

    absolute = tuple(rule for rule in relevance.HARD_EXCLUSION
                     if rule[0] in relevance.NON_OPPORTUNITY_HARD_LABELS)
    return f"""-- GENERATED by tools/export_relevance_sql.py from radar/relevance.py.
-- Do not edit by hand; regenerate when the rule tables change.
create or replace function startup_radar.gfc_relevance_v1_3(
 p_title text,p_applicant text,p_support text)
returns jsonb language plpgsql immutable security invoker set search_path='' as $fn$
declare
 t text; title_text text; applicant_text text; startup_candidate boolean; hard text; absolute_title text;
 generic text; event text; deliverable text;
 core text[]:='{{}}'; restriction text[]:='{{}}';
 core_reason text; restriction_summary text; region text; region_hit text[]; region_summary text;
 eligibility_hit text[]; eligibility_pattern text; eligibility_sentence text;
 industry_field integer; industry_sentence text; industry_hit text[];
 industry_restricted boolean:=false;
begin
 t:=concat_ws(E'\\n',coalesce(p_title,''),
   {evidence('p_applicant', relevance.APPLICANT_EVIDENCE_CHARS)},
   {evidence('p_support', relevance.SUPPORT_EVIDENCE_CHARS)});
 title_text:=coalesce(p_title,'');
 applicant_text:=coalesce(p_applicant,'');
 foreach eligibility_pattern in array array['{sql_regex(relevance._ELIGIBILITY_LABEL.pattern)}',
  '{sql_regex(relevance._ELIGIBILITY_ARROW.pattern)}'] loop
  for eligibility_hit in select regexp_matches(coalesce(p_support,''),eligibility_pattern,'g') loop
   if btrim(eligibility_hit[1])<>'' and not btrim(eligibility_hit[1]) ~* '{sql_regex(relevance._BENEFIT_ARROW.pattern)}' then
    applicant_text:=concat_ws(E'\\n',applicant_text,btrim(eligibility_hit[1]));
   end if;
  end loop;
 end loop;
{curation_branches()}
 startup_candidate:=t ~* '{sql_regex(relevance.STARTUP_CONTEXT.pattern)}'
   and concat_ws(E'\\n',coalesce(p_title,''),coalesce(p_support,'')) ~* '{sql_regex(relevance.PROGRAM_INTENT.pattern)}';
{branches(relevance.HARD_EXCLUSION, 'hard')}
{collected(relevance.CORE_STARTUP, 'core')}
 core_reason:=left(array_to_string(core,' · '),200);
{branches(absolute, 'absolute_title', 'title_text')}
 if absolute_title is not null then
  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',
   'applicability','UNKNOWN','startup_leverage_reason',absolute_title,'restriction_summary',null); end if;
 -- Industry vocabulary is not itself an eligibility condition. Mirror the
 -- contextual audience/advisory checks in relevance._industry_restriction.
 for industry_field in 1..2 loop
  if industry_field=2 and applicant_text ~* '{sql_regex(relevance._BROAD_INDUSTRY.pattern)}' then continue; end if;
  foreach industry_sentence in array regexp_split_to_array(
   (array[applicant_text,title_text])[industry_field],'{sql_regex(relevance._INDUSTRY_CLAUSE_SPLIT.pattern)}') loop
   if industry_sentence ~* '{sql_regex(relevance._INDUSTRY_ADVISORY.pattern)}' then continue; end if;
   for industry_hit in select regexp_matches(industry_sentence,
    '({sql_regex(relevance._INDUSTRY.pattern)})(.{{0,100}})','gi') loop
    if industry_hit[2] ~* '{sql_regex(relevance._INDUSTRY_AUDIENCE.pattern)}' then
     industry_restricted:=true; exit;
    end if;
   end loop;
   exit when industry_restricted;
  end loop;
  exit when industry_restricted;
 end loop;
 if industry_restricted then restriction:=array['특정 산업 분야 한정'::text]; end if;
 foreach eligibility_sentence in array regexp_split_to_array(applicant_text,'{sql_regex(relevance._INDUSTRY_CLAUSE_SPLIT.pattern)}') loop
  if eligibility_sentence ~* '{sql_regex(relevance._ELIGIBILITY_SOFT.pattern)}' then continue; end if;
{collected(relevance.RESTRICTION, 'restriction', 'eligibility_sentence')}
 end loop;
 foreach eligibility_sentence in array regexp_split_to_array(applicant_text,'{sql_regex(relevance._INDUSTRY_CLAUSE_SPLIT.pattern)}') loop
  if eligibility_sentence ~* '{sql_regex(relevance._REGION_SOFT.pattern)}' then continue; end if;
  region_hit:=regexp_match(eligibility_sentence,'{sql_regex(relevance._REGION_TEXT.pattern)}');
  if region_hit is null then region_hit:=regexp_match(eligibility_sentence,'{sql_regex(relevance._REGION_FUTURE.pattern)}'); end if;
  if region_hit is null and not eligibility_sentence ~* '{sql_regex(relevance._REGION_LOCAL.pattern)}' then continue; end if;
  region:=coalesce(region_hit[1],(regexp_match(title_text,'{sql_regex(relevance._REGION_PREFIX.pattern)}'))[1]);
  if region is null then region_summary:='주관지역 소재 조건';
  elsif applicant_text ~* '{sql_regex(relevance._REGION_ALTERNATIVE.pattern)}' then region_summary:=region||' 소재·이전·창업 예정 조건';
  elsif region_hit is not null and eligibility_sentence ~* '{sql_regex(relevance._REGION_TEXT.pattern)}' and region_hit[2]='거주' then region_summary:=region||' 거주 조건';
  elsif applicant_text ~* '{sql_regex(relevance._PERSON_AUDIENCE.pattern)}' then region_summary:=region||' 지역 조건';
  else region_summary:=region||' 소재 기업'; end if;
  restriction:=restriction||region_summary; exit;
 end loop;
 restriction_summary:=nullif(left(array_to_string(restriction,' · '),200),'');
 if hard is not null and cardinality(core)>0 and startup_candidate then
  return jsonb_build_object('relevance_status','REVIEW_REQUIRED','startup_leverage','UNKNOWN',
   'applicability','UNKNOWN','startup_leverage_reason','지원 내용에 서로 다른 신호가 있어 원문 확인 필요',
   'restriction_summary',restriction_summary); end if;
 if hard is not null then
  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',
   'applicability','UNKNOWN','startup_leverage_reason',hard,'restriction_summary',null); end if;
{branches(relevance.GENERIC_SOFT_EXCLUSION, 'generic')}
{branches(relevance.EVENT_SOFT_EXCLUSION, 'event')}
{branches(relevance.DELIVERABLE, 'deliverable')}
 if event is not null and deliverable is null then
  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',
   'applicability','UNKNOWN','startup_leverage_reason',event,'restriction_summary',null); end if;
 if generic is not null and cardinality(core)=0 then
  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',
   'applicability','UNKNOWN','startup_leverage_reason',generic,'restriction_summary',null); end if;
 if cardinality(core)=0 then
  if startup_candidate then
   return jsonb_build_object('relevance_status','REVIEW_REQUIRED','startup_leverage','UNKNOWN',
    'applicability','UNKNOWN','startup_leverage_reason','창업 관련 공고이나 구체적인 지원 내용 확인 필요',
    'restriction_summary',restriction_summary); end if;
  return jsonb_build_object('relevance_status','OUT_OF_SCOPE','startup_leverage','LOW',
   'applicability','UNKNOWN','startup_leverage_reason','창업 실행 레버리지 근거 없음',
   'restriction_summary',null); end if;
 if cardinality(restriction)=0 then
  return jsonb_build_object('relevance_status','GFC_RELEVANT','startup_leverage','HIGH',
   'applicability','BROAD','startup_leverage_reason',core_reason,'restriction_summary',null); end if;
 restriction_summary:=left(array_to_string(restriction,' · '),200);
 return jsonb_build_object('relevance_status','CONDITIONAL','startup_leverage','HIGH',
  'applicability','RESTRICTED','startup_leverage_reason',core_reason,
  'restriction_summary',restriction_summary);
end $fn$;
revoke all on function startup_radar.gfc_relevance_v1_3(text,text,text) from public,anon,authenticated;
grant execute on function startup_radar.gfc_relevance_v1_3(text,text,text) to service_role;
"""


if __name__ == '__main__':
    sys.stdout.write(generate())
